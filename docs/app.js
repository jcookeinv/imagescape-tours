  scene3.add(new THREE.Mesh(new THREE.PlaneBufferGeometry(2, 2), mat));

  // ---------- photos: preview first, full resolution on demand ----------
  var store = {}, fullOrder = [];
  function entry(id) { return store[id] || (store[id] = { prev: null, full: null, pp: null, fp: null }); }
  function loadImg(url) {
    return new Promise(function (res, rej) { var im = new Image(); im.onload = function () { res(im); }; im.onerror = function () { rej(new Error(url)); }; im.src = url; });
  }
  function mkTex(im) {
    var src = im;
    if (im.width > MAXTEX) { var c = document.createElement("canvas"); c.width = MAXTEX; c.height = MAXTEX / 2; c.getContext("2d").drawImage(im, 0, 0, c.width, c.height); src = c; }
    var t = new THREE.Texture(src);
    t.minFilter = THREE.LinearFilter; t.magFilter = THREE.LinearFilter; t.generateMipmaps = false;
    t.wrapS = THREE.RepeatWrapping; t.wrapT = THREE.ClampToEdgeWrapping; t.needsUpdate = true;
    return t;
  }
  function ensurePrev(id) { var e = entry(id); return e.pp || (e.pp = loadImg("img/" + id + "_preview.jpg").then(mkTex).then(function (t) { e.prev = t; return t; })); }
  function ensureFull(id) {
    var e = entry(id);
    return e.fp || (e.fp = loadImg("img/" + id + ".jpg").then(mkTex).then(function (t) {
      e.full = t; fullOrder = fullOrder.filter(function (x) { return x !== id; }); fullOrder.push(id);
      while (fullOrder.length > 4) {            // keep GPU memory in check: drop the oldest full-size photo not in use
        var old = fullOrder.shift();
        if (old === cur || (trans && trans.id === old)) { fullOrder.push(old); break; }
        var o = entry(old); if (o.full) o.full.dispose(); o.full = null; o.fp = null;
      }
      applyTex(id); return t;
    }).catch(function () { e.fp = null; }));
  }
  function texFor(id) { var e = entry(id); return e.full || e.prev; }
  function applyTex(id) {
    if (cur === id) uniforms.tA.value = texFor(id);
    if (trans && trans.id === id) uniforms.tB.value = texFor(id);
    updateSharp();
  }
  function updateSharp() { sharp.hidden = !(cur && !trans && !entry(cur).full); }
  function prefetchAround(id) {
    var s = SC[id];
    ensureFull(id).then(function () { [ORDER[s.i + 1], ORDER[s.i - 1]].forEach(function (n) { if (n) ensureFull(n); }); });
  }

