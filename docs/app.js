  function clampView() {
    view.pitch = Math.max(-60, Math.min(60, view.pitch));
    view.fov = Math.max(24, Math.min(75, view.fov));
    if (view.yaw > 180) view.yaw -= 360; if (view.yaw < -180) view.yaw += 360;
  }

